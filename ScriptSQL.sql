-- NutriLacteos: remote database installation for MySQL 8.0.16 or later.
-- Creates the database, tables, indexes, constraints, and foreign-key relationships.
-- Loads only the identification-type and Ubigeo catalogs required by the contact form.
-- Does not insert sample organizations, responsible people, or contact requests.
-- Run on a new or empty schema; this script does not drop existing objects.

CREATE DATABASE IF NOT EXISTS nutrilacteos
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE nutrilacteos;

CREATE TABLE TYPE_IDENTIFICATION (
    id_type_identification INT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(2) NOT NULL,
    description VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active',
    PRIMARY KEY (id_type_identification),
    CONSTRAINT UQ_TYPE_IDENTIFICATION_CODE UNIQUE (code),
    CONSTRAINT CK_TYPE_IDENTIFICATION_STATUS
        CHECK (status IN ('Active', 'Inactive'))
) ENGINE=InnoDB;

CREATE TABLE UBIGEO (
    id_ubigeo INT UNSIGNED NOT NULL AUTO_INCREMENT,
    department_name VARCHAR(100) NOT NULL,
    province_name VARCHAR(100) NOT NULL,
    district_name VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_ubigeo),
    CONSTRAINT UQ_UBIGEO_LOCATION
        UNIQUE (department_name, province_name, district_name)
) ENGINE=InnoDB;

CREATE TABLE ORGANIZATION (
    id_organization INT UNSIGNED NOT NULL AUTO_INCREMENT,
    id_type_identification INT UNSIGNED NOT NULL,
    id_ubigeo INT UNSIGNED NOT NULL,
    name_organization VARCHAR(150) NOT NULL,
    tax_identification VARCHAR(20) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    street_address VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active',
    registration_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_organization),
    CONSTRAINT UQ_ORGANIZATION_TAX_ID
        UNIQUE (id_type_identification, tax_identification),
    INDEX IDX_ORGANIZATION_UBIGEO (id_ubigeo),
    CONSTRAINT FK_ORGANIZATION_TYPE_IDENTIFICATION
        FOREIGN KEY (id_type_identification)
        REFERENCES TYPE_IDENTIFICATION (id_type_identification)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_ORGANIZATION_UBIGEO
        FOREIGN KEY (id_ubigeo)
        REFERENCES UBIGEO (id_ubigeo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_ORGANIZATION_STATUS
        CHECK (status IN ('Active', 'Inactive'))
) ENGINE=InnoDB;

CREATE TABLE RESPONSIBLE (
    id_responsible INT UNSIGNED NOT NULL AUTO_INCREMENT,
    id_organization INT UNSIGNED NOT NULL,
    name_responsible VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    number VARCHAR(20) NULL,
    post VARCHAR(100) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active',
    date_record DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_responsible),
    CONSTRAINT UQ_RESPONSIBLE_ORGANIZATION_EMAIL
        UNIQUE (id_organization, email),
    INDEX IDX_RESPONSIBLE_ORGANIZATION (id_organization),
    CONSTRAINT FK_RESPONSIBLE_ORGANIZATION
        FOREIGN KEY (id_organization)
        REFERENCES ORGANIZATION (id_organization)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_RESPONSIBLE_STATUS
        CHECK (status IN ('Active', 'Inactive'))
) ENGINE=InnoDB;

CREATE TABLE REQUEST_CONTACT (
    id_request INT UNSIGNED NOT NULL AUTO_INCREMENT,
    id_responsible INT UNSIGNED NOT NULL,
    description VARCHAR(500) NULL,
    date_request DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    observation VARCHAR(300) NULL,
    date_attention DATETIME NULL,
    PRIMARY KEY (id_request),
    INDEX IDX_REQUEST_CONTACT_RESPONSIBLE (id_responsible),
    CONSTRAINT FK_REQUEST_CONTACT_RESPONSIBLE
        FOREIGN KEY (id_responsible)
        REFERENCES RESPONSIBLE (id_responsible)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_REQUEST_CONTACT_STATUS
        CHECK (status IN ('Pending', 'In Progress', 'Attended', 'Cancelled')),
    CONSTRAINT CK_REQUEST_CONTACT_ATTENTION_DATE
        CHECK (date_attention IS NULL OR date_attention >= date_request)
) ENGINE=InnoDB;

-- Tabla para autenticación y registro de usuarios
CREATE TABLE IF NOT EXISTS USERS (
    id_user INT UNSIGNED NOT NULL AUTO_INCREMENT,
    full_name VARCHAR(150) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    registration_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_user)
) ENGINE=InnoDB;

